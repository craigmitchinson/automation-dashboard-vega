// ---------------------------------------------------------------------------
// build.mjs: compiles every panel into a paste-ready Vega spec and one
// Kibana saved-objects file that creates the data view, the panels and the
// dashboards in a single import.
//
//   node vega/build.mjs
//
//   dist/specs/<dashboard>/<panel>.vg.json   paste into a Vega visualisation
//   dist/kibana/ia-dashboards.ndjson         Stack Management > Saved objects > Import
//   dist/manifest.json                       panel list + grid positions (used by the preview)
// ---------------------------------------------------------------------------
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CONFIG, IDX } from "./lib/tokens.mjs";
import { DASHBOARDS, GROUPS } from "./panels/index.mjs";
import { readFileSync } from "node:fs";
import { referenceDocs } from "../etl/reference-impl/pipeline.mjs";
import { RULES, ruleObject } from "./alert-rules.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
rmSync(join(dist, "specs"), { recursive: true, force: true });
mkdirSync(join(dist, "kibana"), { recursive: true });

// Saved-object format target. Kibana refuses objects stamped with a newer
// version than itself, so build for yours: KIBANA_VERSION=8.11.0 npm run build.
// NO_CONTROLS=1 leaves the dashboard controls out (add them by hand) if your
// version rejects the control-group format. NO_RULES=1 leaves the five alerting
// rules out (create them by hand from docs/JOBS.md) if the import refuses them.
const KIBANA_VERSION = process.env.KIBANA_VERSION || "8.15.0";
const NO_CONTROLS = !!process.env.NO_CONTROLS;
const NO_RULES = !!process.env.NO_RULES;
const vnum = (v) => v.split(".").map(Number).reduce((a, n) => a * 1000 + n, 0);
const capped = (v) => (vnum(v) > vnum(KIBANA_VERSION) ? KIBANA_VERSION : v); // never newer than the target
const DATA_VIEW_ID = "ia-workqueue-items";
// Navigation: a Kibana Links panel (8.12+), which carries filters and the time
// range between dashboards; NAV=markdown (or an older Kibana) uses a markdown strip.
const LINKS = process.env.NAV !== "markdown" && vnum(KIBANA_VERSION) >= vnum("8.12.0");

function finalise(dash, panel) {
  const frag = panel.build();
  const spec = {
    $schema: "https://vega.github.io/schema/vega/v5.json",
    description: `${dash.title} · ${panel.title}. Generated by vega/build.mjs from vega/panels/${dash.id}.mjs, do not edit by hand.`,
    autosize: { type: "fit", contains: "padding" },
    padding: 0,
    config: CONFIG,
    signals: frag.signals,
    data: frag.data,
    scales: frag.scales,
    marks: frag.marks,
  };
  // de-duplicate data/signals/scales repeated by merged blocks (first wins)
  for (const k of ["signals", "data", "scales"]) {
    const seen = new Set();
    spec[k] = spec[k].filter((d) => (seen.has(d.name) ? false : (seen.add(d.name), true)));
    if (!spec[k].length) delete spec[k];
  }
  return spec;
}

const manifest = [];
const objects = [];

objects.push({
  id: DATA_VIEW_ID,
  type: "index-pattern",
  attributes: { title: IDX.dataView, name: "IA work-queue items", timeFieldName: "@timestamp" },
  references: [],
  coreMigrationVersion: KIBANA_VERSION,
  typeMigrationVersion: capped("8.0.0"),
});

if (LINKS) {
  const links = DASHBOARDS.map((d, i) => ({
    id: `ia-link-${d.id}`,
    type: "dashboardLink",
    order: i,
    label: d.title.replace(/^IA · /, ""),
    destinationRefName: `link_ia-link-${d.id}_dashboard`,
    options: { openInNewTab: false, useCurrentFilters: true, useCurrentDateRange: true },
  }));
  objects.push({
    id: "ia-links",
    type: "links",
    attributes: { title: "IA · Navigation", description: "The IA dashboards, in order. Carries filters and the time range.", layout: "horizontal", links },
    references: DASHBOARDS.map((d) => ({ name: `link_ia-link-${d.id}_dashboard`, type: "dashboard", id: `ia-${d.id}` })),
    coreMigrationVersion: KIBANA_VERSION,
  });
}
const navMarkdown = GROUPS.map((g) => `**${g.name}** ` + g.dashboards.map((d) => `[${d.title.replace(/^IA · /, "")}](#/view/ia-${d.id})`).join(" · ")).join("  |  ");
objects.push({
  id: "ia-nav",
  type: "visualization",
  attributes: {
    title: "IA · Navigation",
    description: "Links between the IA dashboards (keeps time range; use a Links panel to carry filters too).",
    visState: JSON.stringify({ title: "IA · Navigation", type: "markdown", aggs: [], params: { markdown: navMarkdown, openLinksInNewTab: false, fontSize: 11 } }),
    uiStateJSON: "{}",
    version: 1,
    kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
  },
  references: [],
  coreMigrationVersion: KIBANA_VERSION,
  typeMigrationVersion: capped("8.5.0"),
});

const CONTROLS = [
  { field: "spoke.name", title: "Spoke" },
  { field: "proposition.name", title: "Proposition" },
  { field: "process.name", title: "Process" },
  { field: "queue.name", title: "Queue" },
  { field: "process.tags", title: "Tags" },
];

for (const dash of DASHBOARDS) {
  const panelsJSON = [];
  const refs = [];
  // navigation strip on top, everything else shifted down by 2 rows
  panelsJSON.push({ type: LINKS ? "links" : "visualization", gridData: { x: 0, y: 0, w: 48, h: 2, i: "nav" }, panelIndex: "nav", embeddableConfig: { hidePanelTitles: true, enhancements: {} }, panelRefName: "panel_nav", version: KIBANA_VERSION });
  refs.push({ name: "panel_nav", type: LINKS ? "links" : "visualization", id: LINKS ? "ia-links" : "ia-nav" });

  for (const panel of dash.panels) {
    const spec = finalise(dash, panel);
    const json = JSON.stringify(spec, null, 2);
    const file = join(dist, "specs", dash.id, `${panel.id}.vg.json`);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, json + "\n");
    const visId = `ia-${dash.id}-${panel.id}`;
    objects.push({
      id: visId,
      type: "visualization",
      attributes: {
        title: `${dash.title} · ${panel.title}`,
        description: "",
        visState: JSON.stringify({ title: `${dash.title} · ${panel.title}`, type: "vega", aggs: [], params: { spec: json } }),
        uiStateJSON: "{}",
        version: 1,
        kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
      },
      references: [],
      coreMigrationVersion: KIBANA_VERSION,
      typeMigrationVersion: capped("8.5.0"),
    });
    const gid = panel.id;
    panelsJSON.push({
      type: "visualization",
      gridData: { ...panel.grid, y: panel.grid.y + 2, i: gid },
      panelIndex: gid,
      embeddableConfig: { hidePanelTitles: true, enhancements: {} },
      panelRefName: `panel_${gid}`,
      version: KIBANA_VERSION,
    });
    refs.push({ name: `panel_${gid}`, type: "visualization", id: visId });
    manifest.push({ dashboard: dash.id, dashboardTitle: dash.title, controls: (NO_CONTROLS ? [] : dash.controls ?? [...CONTROLS, ...(dash.extraControls ?? [])]).map((c) => c.title), panel: panel.id, title: panel.title, grid: panel.grid, file: `dist/specs/${dash.id}/${panel.id}.vg.json`, states: panel.states ?? dash.states ?? null, preview: dash.preview ?? null });
  }

  const controls = {};
  (NO_CONTROLS ? [] : dash.controls ?? [...CONTROLS, ...(dash.extraControls ?? [])]).forEach((c, order) => {
    const cid = `${dash.id}-${c.field.replace(/\W/g, "-")}`;
    controls[cid] = { order, width: "medium", grow: true, type: "optionsListControl", explicitInput: { id: cid, fieldName: c.field, title: c.title, selectedOptions: [], enhancements: {} } };
    refs.push({ name: `controlGroup_${cid}:optionsListDataView`, type: "index-pattern", id: DATA_VIEW_ID });
  });

  objects.push({
    id: `ia-${dash.id}`,
    type: "dashboard",
    attributes: {
      title: dash.title,
      description: dash.description,
      panelsJSON: JSON.stringify(panelsJSON),
      optionsJSON: JSON.stringify({ useMargins: true, syncColors: false, syncCursor: true, syncTooltips: false, hidePanelTitles: true }),
      timeRestore: true,
      timeFrom: dash.time.from,
      timeTo: dash.time.to,
      refreshInterval: { pause: true, value: 60000 },
      ...(NO_CONTROLS ? {} : { controlGroupInput: {
        chainingSystem: "HIERARCHICAL",
        controlStyle: "oneLine",
        ignoreParentSettingsJSON: JSON.stringify({ ignoreFilters: false, ignoreQuery: false, ignoreTimerange: false, ignoreValidations: false }),
        panelsJSON: JSON.stringify(controls),
        showApplySelections: false,
      } }),
      kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
    },
    references: refs,
    coreMigrationVersion: KIBANA_VERSION,
    typeMigrationVersion: capped("8.9.0"),
  });
}

if (!NO_RULES) for (const r of RULES) objects.push(ruleObject(r, KIBANA_VERSION, capped));
writeFileSync(join(dist, "kibana", "ia-dashboards.ndjson"), objects.map((o) => JSON.stringify(o)).join("\n") + "\n");
writeFileSync(join(dist, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(join(dist, "nav.json"), JSON.stringify(GROUPS.map((g) => [g.name, g.dashboards.map((d) => d.title.replace("IA · ", ""))])) + "\n");

// ia-reference as _bulk NDJSON, so setup/install.py needs no Node on the host.
// Current grade rates are as at the build date: rebuild when reference.json changes.
{
  const ref = JSON.parse(readFileSync(join(root, "etl", "reference", "reference.json"), "utf8"));
  const docs = referenceDocs(ref, new Date().toISOString().slice(0, 10));
  mkdirSync(join(dist, "elasticsearch"), { recursive: true });
  writeFileSync(join(dist, "elasticsearch", "ia-reference.ndjson"), docs.map((d) => JSON.stringify({ index: { _index: "ia-reference" } }) + "\n" + JSON.stringify(d)).join("\n") + "\n");

  // Everything Elasticsearch needs, as one file to paste into Kibana Dev Tools:
  // the four index templates, then the reference data. No scripts, no API keys.
  const tpl = ["ia-workqueue-items", "ia-cost-daily", "ia-vdi-daily", "ia-reference"];
  const parts = [
    "# IA dashboards: Elasticsearch setup. Paste into Kibana > Dev Tools > Console, select all, and run (Ctrl+Enter).",
    "# Safe to re-run. Built " + new Date().toISOString().slice(0, 10) + ".",
    "",
    ...tpl.flatMap((t) => [`PUT _index_template/${t}`, JSON.stringify(JSON.parse(readFileSync(join(root, "etl", "index-templates", `${t}.json`), "utf8")), null, 2), ""]),
    "# Empty indices, so every panel renders before Logstash has run (a re-run answers resource_already_exists, which is fine)",
    ...["ia-workqueue-items", "ia-cost-daily", "ia-vdi-daily"].flatMap((i) => [`PUT ${i}`, ""]),
    "# Reference data: delete and reload so removed rows go too (the 404 on a first run is expected)",
    "DELETE ia-reference",
    "",
    "POST _bulk?refresh=true",
    ...docs.flatMap((d) => [JSON.stringify({ index: { _index: "ia-reference" } }), JSON.stringify(d)]),
    "",
  ];
  writeFileSync(join(dist, "kibana", "devtools-setup.txt"), parts.join("\n"));
}
console.log(`built ${manifest.length} panels across ${DASHBOARDS.length} dashboards (saved objects for Kibana ${KIBANA_VERSION}, ${LINKS ? "Links panel" : "markdown"} navigation${NO_CONTROLS ? ", no controls" : ""}${NO_RULES ? ", no alert rules" : `, ${RULES.length} alert rules`})`);
