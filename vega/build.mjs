// ---------------------------------------------------------------------------
// build.mjs — compiles every panel into a paste-ready Vega spec and one
// Kibana saved-objects file that creates the data view, the panels and the
// dashboards in a single import.
//
//   node vega/build.mjs
//
//   dist/specs/<dashboard>/<panel>.vg.json   paste into a Vega visualisation
//   dist/kibana/ia-dashboards.ndjson         Stack Management > Saved objects > Import
//   dist/manifest.json                       panel list + grid positions (used by the preview)
// ---------------------------------------------------------------------------
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CONFIG, IDX } from "./lib/tokens.mjs";
import { DASHBOARDS } from "./panels/index.mjs";
import { SERVICE, CHECKS, SERVICE_QUERIES, STATUS_RANK, STATUS_LABEL } from "./lib/service.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
rmSync(join(dist, "specs"), { recursive: true, force: true });
mkdirSync(join(dist, "kibana"), { recursive: true });

const KIBANA_VERSION = "8.15.0"; // saved-object format target; see docs/KIBANA-SETUP.md
const DATA_VIEW_ID = "ia-workqueue-items";

function finalise(dash, panel) {
  const frag = panel.build();
  const spec = {
    $schema: "https://vega.github.io/schema/vega/v5.json",
    description: `${dash.title} · ${panel.title}. Generated by vega/build.mjs from vega/panels/${dash.id}.mjs, do not edit by hand.`,
    autosize: { type: "fit", contains: "padding" },
    padding: 0,
    config: CONFIG,
    signals: frag.signals,
    data: frag.data,
    scales: frag.scales,
    marks: frag.marks,
  };
  // de-duplicate data/signals/scales repeated by merged blocks (first wins)
  for (const k of ["signals", "data", "scales"]) {
    const seen = new Set();
    spec[k] = spec[k].filter((d) => (seen.has(d.name) ? false : (seen.add(d.name), true)));
    if (!spec[k].length) delete spec[k];
  }
  return spec;
}

const manifest = [];
const objects = [];

objects.push({
  id: DATA_VIEW_ID,
  type: "index-pattern",
  attributes: { title: IDX.dataView, name: "IA work-queue items", timeFieldName: "@timestamp" },
  references: [],
  coreMigrationVersion: KIBANA_VERSION,
  typeMigrationVersion: "8.0.0",
});

const navMarkdown = DASHBOARDS.map((d) => `[${d.title.replace(/^IA · /, "")}](#/view/ia-${d.id})`).join(" · ");
objects.push({
  id: "ia-nav",
  type: "visualization",
  attributes: {
    title: "IA · Navigation",
    description: "Links between the IA dashboards (keeps time range; use a Links panel to carry filters too).",
    visState: JSON.stringify({ title: "IA · Navigation", type: "markdown", aggs: [], params: { markdown: navMarkdown, openLinksInNewTab: false, fontSize: 11 } }),
    uiStateJSON: "{}",
    version: 1,
    kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
  },
  references: [],
  coreMigrationVersion: KIBANA_VERSION,
  typeMigrationVersion: "8.5.0",
});

const CONTROLS = [
  { field: "spoke.name", title: "Spoke" },
  { field: "proposition.name", title: "Proposition" },
  { field: "process.name", title: "Process" },
  { field: "queue.name", title: "Queue" },
  { field: "process.tags", title: "Tags" },
];

for (const dash of DASHBOARDS) {
  const panelsJSON = [];
  const refs = [];
  // navigation strip on top, everything else shifted down by 2 rows
  panelsJSON.push({ type: "visualization", gridData: { x: 0, y: 0, w: 48, h: 2, i: "nav" }, panelIndex: "nav", embeddableConfig: { hidePanelTitles: true, enhancements: {} }, panelRefName: "panel_nav", version: KIBANA_VERSION });
  refs.push({ name: "panel_nav", type: "visualization", id: "ia-nav" });

  for (const panel of dash.panels) {
    const spec = finalise(dash, panel);
    const json = JSON.stringify(spec, null, 2);
    const file = join(dist, "specs", dash.id, `${panel.id}.vg.json`);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, json + "\n");
    const visId = `ia-${dash.id}-${panel.id}`;
    objects.push({
      id: visId,
      type: "visualization",
      attributes: {
        title: `${dash.title} · ${panel.title}`,
        description: "",
        visState: JSON.stringify({ title: `${dash.title} · ${panel.title}`, type: "vega", aggs: [], params: { spec: json } }),
        uiStateJSON: "{}",
        version: 1,
        kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
      },
      references: [],
      coreMigrationVersion: KIBANA_VERSION,
      typeMigrationVersion: "8.5.0",
    });
    const gid = panel.id;
    panelsJSON.push({
      type: "visualization",
      gridData: { ...panel.grid, y: panel.grid.y + 2, i: gid },
      panelIndex: gid,
      embeddableConfig: { hidePanelTitles: true, enhancements: {} },
      panelRefName: `panel_${gid}`,
      version: KIBANA_VERSION,
    });
    refs.push({ name: `panel_${gid}`, type: "visualization", id: visId });
    manifest.push({ dashboard: dash.id, dashboardTitle: dash.title, panel: panel.id, title: panel.title, grid: panel.grid, file: `dist/specs/${dash.id}/${panel.id}.vg.json`, states: panel.states ?? dash.states ?? null, preview: dash.preview ?? null });
  }

  const controls = {};
  (dash.controls ?? CONTROLS).forEach((c, order) => {
    const cid = `${dash.id}-${c.field.replace(/\W/g, "-")}`;
    controls[cid] = { order, width: "medium", grow: true, type: "optionsListControl", explicitInput: { id: cid, fieldName: c.field, title: c.title, selectedOptions: [], enhancements: {} } };
    refs.push({ name: `controlGroup_${cid}:optionsListDataView`, type: "index-pattern", id: DATA_VIEW_ID });
  });

  objects.push({
    id: `ia-${dash.id}`,
    type: "dashboard",
    attributes: {
      title: dash.title,
      description: dash.description,
      panelsJSON: JSON.stringify(panelsJSON),
      optionsJSON: JSON.stringify({ useMargins: true, syncColors: false, syncCursor: true, syncTooltips: false, hidePanelTitles: true }),
      timeRestore: true,
      timeFrom: dash.time.from,
      timeTo: dash.time.to,
      refreshInterval: { pause: true, value: 60000 },
      controlGroupInput: {
        chainingSystem: "HIERARCHICAL",
        controlStyle: "oneLine",
        ignoreParentSettingsJSON: JSON.stringify({ ignoreFilters: false, ignoreQuery: false, ignoreTimerange: false, ignoreValidations: false }),
        panelsJSON: JSON.stringify(controls),
        showApplySelections: false,
      },
      kibanaSavedObjectMeta: { searchSourceJSON: JSON.stringify({ query: { query: "", language: "kuery" }, filter: [] }) },
    },
    references: refs,
    coreMigrationVersion: KIBANA_VERSION,
    typeMigrationVersion: "8.9.0",
  });
}

writeFileSync(join(dist, "kibana", "ia-dashboards.ndjson"), objects.map((o) => JSON.stringify(o)).join("\n") + "\n");
writeFileSync(join(dist, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

// The service check job runs exactly the queries and thresholds the Service
// dashboard uses (vega/lib/service.mjs), so it reads them from this file.
mkdirSync(join(root, "etl", "service-job"), { recursive: true });
writeFileSync(
  join(root, "etl", "service-job", "service-checks.json"),
  JSON.stringify({ _generated: "by vega/build.mjs from vega/lib/service.mjs; do not edit", service: SERVICE, checks: CHECKS, statusRank: STATUS_RANK, statusLabel: STATUS_LABEL, queries: SERVICE_QUERIES }, null, 2) + "\n",
);
console.log(`built ${manifest.length} panels across ${DASHBOARDS.length} dashboards`);
